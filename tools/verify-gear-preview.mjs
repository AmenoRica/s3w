import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../gear/app.js',import.meta.url),'utf8');
const nodes=new Map();
const animation=()=>({playState:'running',currentTime:42,pause(){this.playState='paused';},play(){this.playState='running';},finish(){this.playState='finished';},cancel(){this.playState='idle';}});
const context=vm.createContext({languageCode:()=> 'en-US',t:x=>x,number:String,paused:false,document:{body:{classList:{toggle(){}}}},requestAnimationFrame(){},cancelAnimationFrame(){},$:id=>nodes.get(id)});
vm.runInContext(source.slice(source.indexOf('const seconds ='),source.indexOf('let dragSource')),context);
for(const [frames,expected] of [[0,'0.00'],[1,'0.02'],[80,'1.34'],[138,'2.30'],[190,'3.17'],[218,'3.64'],[450,'7.50']])assert.equal(vm.runInContext(`seconds(${frames})`,context),expected);
const button={},a=animation();context.button=button;context.a=a;
vm.runInContext('manualStart(button,[a])',context);
assert.equal(a.playState,'paused');assert.equal(a.currentTime,0);
button.onclick();assert.equal(a.playState,'running');
a.finish();a.currentTime=500;button.onclick();assert.equal(a.currentTime,0);assert.equal(a.playState,'running');
vm.runInContext('paused=true',context);button.onclick();assert.equal(a.playState,'finished');
vm.runInContext('paused=false; var jumpAnimation,phaseAnimationId; var result={jump:{chargeFrames:80,arrivalMax:218}};',context);
nodes.set('jump-start',{});nodes.set('jump-emoji',{classList:{toggle(){}}});
let keyframes,timing;
nodes.set('jumper',{animate(k,t){keyframes=k;timing=t;return animation();}});
vm.runInContext(source.slice(source.indexOf('function animateJump()'),source.indexOf('function applyMotion()')),context);
vm.runInContext('animateJump()',context);
assert.equal(timing.iterations,1);assert.equal(timing.fill,'forwards');assert.equal(keyframes[0].left,'0%');assert.equal(keyframes.at(-1).left,'0%');assert.ok(keyframes.some(k=>k.left==='100%'));
assert.equal(vm.runInContext('jumpAnimation.playState',context),'paused');
nodes.get('jump-start').onclick();assert.equal(vm.runInContext('jumpAnimation.playState',context),'running');
console.log('PASS: seconds rounding, start/restart, reduced motion, single round-trip jump.');
