import assert from 'node:assert/strict';
import {createWeaponDrag,outsideMarkerBounds} from '../stages/weapons.js';
let changed=0,selected=[];
const canvas={getBoundingClientRect:()=>({left:10,top:20})};
const node={classList:{add(){},remove(){}},focus(){},getBoundingClientRect:()=>({left:90,top:90,width:40,height:40}),setPointerCapture(id){this.capture=id},hasPointerCapture(id){return this.capture===id},releasePointerCapture(){this.capture=null}};
const item={position:[1,2,3]};
const drag=createWeaponDrag({canvas,pick:(x,y)=>x<200?[x,7,y]:null,changed:()=>changed++,selected:item=>selected.push(item)});
drag.bind(node,item);
const event=(x,y,extra={})=>({pointerId:1,button:0,isPrimary:true,clientX:x,clientY:y,preventDefault(){},...extra});
node.onpointerdown(event(115,115));node.onpointermove(event(145,155));
assert.deepEqual(item.position,[130,7,130]); // Preserve the initial 5px grab offset.
node.onpointerup(event(155,165));assert.deepEqual(item.position,[140,7,140]);assert.equal(drag.active(),false);
const before=item.position.slice();
node.onpointerdown(event(115,115));node.onpointermove(event(160,170));node.onpointerup(event(300,170));assert.deepEqual(item.position,before);
node.onpointerdown(event(115,115));node.onpointermove(event(160,170));drag.cancel();assert.deepEqual(item.position,before);
node.onpointerdown(event(115,115));node.onpointermove(event(160,170));node.onpointercancel(event(160,170));assert.deepEqual(item.position,before);
node.onpointerdown(event(115,115));node.onpointermove(event(160,170));node.onlostpointercapture(event(160,170));assert.deepEqual(item.position,before);
assert.equal(selected.length,0,'drag and cancellation never select');
const count=changed;node.onpointerdown(event(115,115));node.onpointerup(event(117,116));assert.deepEqual(item.position,before);assert.equal(changed,count);assert.deepEqual(selected,[item]);
node.onpointerdown(event(115,115,{button:2}));assert.equal(drag.active(),false);
node.onpointerdown(event(115,115,{isPrimary:false}));assert.equal(drag.active(),false);
node.onpointerdown(event(115,115));node.onpointermove(event(150,160,{pointerId:2}));assert.deepEqual(item.position,before);drag.cancel();
assert.equal(node.onclick,undefined);
console.log('PASS: live terrain drag, grab offset, valid drop, invalid drop rollback, Escape/cancel/capture loss, click threshold and other pointer rejection.');
let removed=[];
const deletion=createWeaponDrag({canvas,pick:(x,y)=>x<200?[x,7,y]:null,changed(){},outside:x=>x>350,removed:item=>removed.push(item)});
deletion.bind(node,item);
node.onpointerdown(event(115,115));node.onpointerup(event(300,170));assert.equal(removed.length,0,'near invalid terrain returns to origin');
node.onpointerdown(event(115,115));node.onpointermove(event(500,170));deletion.cancel();assert.equal(removed.length,0,'Escape outside never deletes');
node.onpointerdown(event(115,115));node.onpointermove(event(500,170));node.onpointercancel(event(500,170));assert.equal(removed.length,0,'pointer cancel never deletes');
node.onpointerdown(event(115,115));node.onpointermove(event(500,170));node.onpointerup(event(155,165));assert.equal(removed.length,0,'return to terrain saves marker');
node.onpointerdown(event(115,115));node.onpointerup(event(500,170));assert.deepEqual(removed,[item],'release far outside deletes exactly once');
node.onlostpointercapture(event(500,170));assert.equal(removed.length,1);
const bounds={left:100,right:600,top:100,bottom:400};
assert.equal(outsideMarkerBounds(80,200,800,600,bounds),false);
assert.equal(outsideMarkerBounds(60,200,800,600,bounds),true);
assert.equal(outsideMarkerBounds(300,450,800,600,bounds),true);
assert.equal(outsideMarkerBounds(850,200,800,600,null),true);
assert.equal(outsideMarkerBounds(300,200,800,600,bounds),false);
console.log('PASS: far-outside deletion, margin, cancel/return safety and single removal.');
